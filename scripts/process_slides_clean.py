def clean_caption(line):
    line = re.sub(r'\s*\((?:1:1\s*순백색|16:9\s*와이드|정사각|와이드).*?\)', '', line)
    return line

def process_chapter_9_1():
    chapter_path = '/Users/hojin9/dev/jinysite/강화학습3/src/09_몬테카를로법/9_1_몬테카를로법_기초'
    index_md = os.path.join(chapter_path, 'index.md')
    slides_md = os.path.join(chapter_path, 'slides.md')

    raw = open(index_md, 'r', encoding='utf-8').read()
    clean_text = re.sub(r'^---\s*\n.*?\n---\s*\n', '', raw, flags=re.DOTALL).strip()
    sections = re.split(r'\n---\s*\n', clean_text)

    print(f"Total sections to convert: {len(sections)}")
    slides = []

    for idx, s in enumerate(sections):
        lines = s.strip().splitlines()
        slide_title = titles_9_1[idx]
        
        # Clean lines: remove prompt artifacts from captions, keep all text intact
        cleaned_lines = []
        for l in lines:
            l_strip = l.strip()
            # If line is an H1 or H2 or H3, we can preserve it or convert to content
            if l_strip.startswith('# '):
                continue
            elif '그림 09-1-' in l_strip or '**그림' in l_strip:
                cleaned_lines.append(clean_caption(l))
            else:
                cleaned_lines.append(l)

        body_content = "\n".join(cleaned_lines).strip()
        script = scripts_9_1.get(idx + 1, "")

        slide_entry = f"# 09.1 몬테카를로법 기초\n## {slide_title}\n\n{body_content}\n\n> \"{script}\""
        slides.append(slide_entry)

    full_content = "\n\n---\n\n".join(slides) + "\n"
    with open(slides_md, 'w', encoding='utf-8') as f:
        f.write(full_content)

    print(f"🎉 Successfully created {slides_md} with {len(slides)} slides!")

if __name__ == '__main__':
    process_chapter_9_1()
